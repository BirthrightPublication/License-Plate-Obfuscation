const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
(async()=>{
 const profile=await fs.mkdtemp(path.join(os.tmpdir(),'plate-studio-smoke-'));
 const options={headless:true,executablePath:process.env.CHROMIUM_PATH||undefined,viewport:{width:1440,height:1000}};
 let context;
 try{
  context=await chromium.launchPersistentContext(profile,options);
  let page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  const url=process.env.STUDIO_URL||'http://localhost:4173';
  await page.goto(url);
  assert.match(await page.locator('header').innerText(),/v0\.1\.1/);
  assert.equal(await page.locator('#state option').count(),50);
  assert.equal(await page.textContent('#plateText'),'STUDIO');
  await page.selectOption('#state','Texas');await page.fill('#text','abc123');
  assert.equal(await page.textContent('#plateText'),'ABC123');
  await page.fill('#name','Browser test');await page.click('#save');
  assert.match(await page.textContent('#storage'),/saved on this device/);
  const slider=page.locator('#orbit');const bounds=await slider.boundingBox();
  await page.mouse.move(bounds.x+bounds.width*0.38,bounds.y+bounds.height/2);
  await page.mouse.down();await page.mouse.move(bounds.x+bounds.width*0.85,bounds.y+bounds.height/2,{steps:10});await page.mouse.up();
  assert.notEqual(await slider.inputValue(),'-12');
  assert.match(await page.locator('#plate').getAttribute('style'),/rotateY/);
  await page.click('#reset');assert.equal(await slider.inputValue(),'-12');
  await page.click('#availability');assert.match(await page.textContent('#lookup'),/No lookup was sent/);
  assert.equal(await page.locator('.badge').innerText(),'Unverified');
  await page.fill('#notes','Research stays local');
  const downloadPromise=page.waitForEvent('download');await page.click('#export');
  const download=await downloadPromise;const exported=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  assert.deepEqual(exported,{schemaVersion:1,name:'Browser test',state:'Texas',text:'ABC123'});
  await page.fill('#text','OTHER');
  await page.setInputFiles('#import',{name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
  await page.waitForFunction(()=>document.getElementById('text').value==='ABC123');
  await page.setInputFiles('#import',{name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{invalid')});
  await page.waitForFunction(()=>document.getElementById('storage').textContent.startsWith('Import failed:'));
  assert.equal(await page.inputValue('#text'),'ABC123');
  if(process.env.STUDIO_SCREENSHOT)await page.screenshot({path:process.env.STUDIO_SCREENSHOT,fullPage:true});
  await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  await context.close();context=await chromium.launchPersistentContext(profile,options);
  page=await context.newPage();page.on('pageerror',e=>errors.push(String(e)));await page.goto(url);await page.click('#load');
  assert.equal(await page.inputValue('#name'),'Browser test');assert.equal(await page.inputValue('#text'),'ABC123');assert.equal(await page.inputValue('#state'),'Texas');
  assert.equal(await page.inputValue('#notes'),'Research stays local');assert.deepEqual(errors,[]);
  console.log('PASS browser: 50 states, initial rendering, uppercase text, mouse slider/reset, save, actual browser close/reopen/load, export/import, malformed import rejection, notes persistence, unavailable lookup, Unverified legal status, 390px layout, no script errors');
 }finally{if(context)await context.close();await fs.rm(profile,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1;});
